#!/usr/bin/env python3
"""
experiments/generate_publication_docs.py — auto-generate the publication evidence documents.
============================================================================================

Reads the claims/reviewer registry + the executed artifacts and emits, with NO hand-written values:
  CLAIM_EVIDENCE_MATRIX.md          (Part 1)
  reviewer_mapping.md               (Part 2)
  THREATS_TO_VALIDITY.md            (Part 3)
  LIMITATIONS_AND_NEGATIVE_RESULTS.md (Part 6)
  REPRODUCIBILITY_AUDIT.md          (Part 10)
  evidence_manifest.json            (Part 8)
  FINAL_EVIDENCE_REPORT.md          (Part 11) — regenerated from executed evidence

Every status and number is resolved live from artifacts via experiments/_evidence.py.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
ROOT = HERE.parent

import _evidence as EV  # type: ignore
from claims_registry import CLAIMS, REVIEWER_CONCERNS  # type: ignore

EXP = ROOT / "experiments"


def _run_index():
    p = EXP / "_meta" / "run_index.json"
    return json.loads(p.read_text()) if p.exists() else {}


def _host():
    p = EXP / "_meta" / "host.json"
    return json.loads(p.read_text()) if p.exists() else {}


def evaluated_claims():
    return [EV.evaluate_claim(c) for c in CLAIMS]


# ---------------------------------------------------------------- Part 1: claim matrix
def gen_claim_matrix(evals):
    md = ["# CLAIM → EVIDENCE MATRIX (auto-generated)", "",
          "Generated by `experiments/generate_publication_docs.py` from the claims registry and the "
          "executed artifacts. Every status is derived live: each claim's evidence pointer is resolved "
          "against its JSON artifact and the required relation checked. **No value is hand-written.**", "",
          "Chain per claim: **Paper Claim → Experiment → Raw/Processed Artifact → Figure → Table → Status**", "",
          "| Claim | Statement | Experiment(s) | Evidence (artifact ▷ pointer = value) | Figure | Table | Status |",
          "|-------|-----------|---------------|----------------------------------------|--------|-------|--------|"]
    counts = {}
    for e in evals:
        counts[e["status"]] = counts.get(e["status"], 0) + 1
        ev_cells = []
        for chk in e["evidence_checks"]:
            art = chk["artifact"].split("/")[-1]
            mark = "✓" if chk["holds"] else "✗"
            ev_cells.append(f"{mark} {art}▷{chk['pointer']}={chk['value']}")
        ev_str = "<br>".join(ev_cells) if ev_cells else "—"
        figs = ", ".join(e["figures"]) or "—"
        tabs = ", ".join(e["tables"]) or "—"
        exps = ", ".join(e["experiments"]) or "(none)"
        md.append(f"| {e['id']} | {e['statement']} | {exps} | {ev_str} | {figs} | {tabs} | **{e['status']}** |")
    md += ["", "## Status summary"]
    for k, v in sorted(counts.items()):
        md.append(f"- {k}: {v}")
    notes = [e for e in evals if e.get("note")]
    if notes:
        md += ["", "## Notes on partial / not-claimed items"]
        for e in notes:
            md.append(f"- **{e['id']} ({e['status']})**: {e['note']}")
    (ROOT / "CLAIM_EVIDENCE_MATRIX.md").write_text("\n".join(md))
    return counts


# ---------------------------------------------------------------- Part 2: reviewer mapping
def gen_reviewer_mapping(evals):
    by_id = {e["id"]: e for e in evals}
    md = ["# REVIEWER MAPPING (auto-generated, rebuttal-ready)", "",
          "For every anticipated reviewer concern: the experiment(s) that answer it, the evidence "
          "artifact, the paper section, the figure, and the live-derived resolution status.", "",
          "| # | Reviewer concern | Experiment(s) | Evidence artifact | Paper § | Figure | Status |",
          "|---|------------------|---------------|-------------------|---------|--------|--------|"]
    for rc in REVIEWER_CONCERNS:
        statuses = [by_id[cid]["status"] for cid in rc["claims"] if cid in by_id]
        if not statuses:
            resolution = "Pending"
        elif all(s == "Supported" for s in statuses):
            resolution = "Resolved"
        elif all("Not Claimed" in s for s in statuses):
            resolution = "Out of scope (not claimed)"
        elif any("Partially" in s for s in statuses):
            resolution = "Partially resolved"
        elif any("negative" in s.lower() for s in statuses):
            resolution = "Resolved (negative result, disclosed)"
        elif all(("Supported" in s or "negative" in s.lower() or "Not Claimed" in s) for s in statuses):
            resolution = "Resolved"
        else:
            resolution = "Open"
        exps = ", ".join(sorted({x for cid in rc["claims"] for x in by_id.get(cid, {}).get("experiments", [])})) or "—"
        art = (rc.get("artifact_hint") or "—")
        art = art.split("/")[-1] if art != "—" else "—"
        fig = rc.get("figure") or "—"
        md.append(f"| {rc['id']} | {rc['concern']} | {exps} | {art} | {rc['paper_section']} | {fig} | **{resolution}** |")
    md += ["", "## Detailed concern → claim → evidence chains", ""]
    for rc in REVIEWER_CONCERNS:
        md.append(f"### {rc['id']} — {rc['concern']}")
        for cid in rc["claims"]:
            e = by_id.get(cid)
            if not e:
                continue
            md.append(f"- Claim {cid} [{e['status']}]: {e['statement']}")
            for chk in e["evidence_checks"]:
                mark = "✓" if chk["holds"] else "✗"
                md.append(f"    - {mark} `{chk['artifact']}` ▷ `{chk['pointer']}` = `{chk['value']}` "
                          f"(needs `{chk['relation']}`)")
        md.append("")
    (ROOT / "reviewer_mapping.md").write_text("\n".join(md))


