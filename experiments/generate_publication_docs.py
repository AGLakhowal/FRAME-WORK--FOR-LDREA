# ---------------------------------------------------------------- Part 6: limitations & negatives
def gen_limitations(evals):
    idx = _run_index()
    exps = idx.get("experiments", {})
    blocked = []
    for eid, r in exps.items():
        if r.get("blocked_reason") or r.get("missing_dependency"):
            blocked.append((eid, r.get("blocked_reason") or "", r.get("missing_dependency") or "",
                            r.get("rerun_when_available") or ""))
    negatives = [e for e in evals if "negative" in (e["status"].lower())]
    partial = [e for e in evals if "Partially" in e["status"]]
    notclaimed = [e for e in evals if "Not Claimed" in e["status"]]
    md = ["# LIMITATIONS AND NEGATIVE RESULTS (auto-generated)", "",
          "Transparency over persuasion: every limitation, negative result, blocked experiment, and "
          "unclaimed capability, derived from the executed run index and claim statuses.", "",
          "## Negative results (disclosed, not hidden)"]
    if negatives:
        for e in negatives:
            md.append(f"- **{e['id']}** — {e['statement']} (status: {e['status']}).")
    else:
        md.append("- (none detected)")
    md += ["", "## Blocked / dependency-limited experiments"]
    if blocked:
        for eid, reason, dep, rerun in blocked:
            md.append(f"- **{eid}** — {reason or 'blocked'}. Missing dependency: `{dep}`."
                      + (f" Rerun: `{rerun}`" if rerun else ""))
    else:
        md.append("- (none — all experiments executed, E7 included; see the optional live-arm note below)")
    # E7 optional live-arm status, pulled from its metadata substeps. E7 itself is EXECUTED offline;
    # only the agent-side live arm can be absent, and no L-DREA claim depends on it.
    e7 = json.loads((EXP / "agentdojo" / "metadata.json").read_text()) if (EXP / "agentdojo" / "metadata.json").exists() else {}
    le = (e7.get("substeps", {}) or {}).get("live_episodes", {})
    if le.get("status") == "NOT_RUN":
        md.append(f"- **E7 optional live arm (agent-side Utility/TASR)** — NOT_RUN. Missing: "
                  f"`{le.get('missing_dependency')}` (a local Ollama server; no hosted provider is used). "
                  f"E7's own status is `{(e7.get('run') or {}).get('status')}` — every runtime-governance "
                  f"metric is measured offline. Rerun: `{le.get('rerun')}`")
    md += ["", "## Partially supported claims"]
    md += ([f"- **{e['id']}** — {e['statement']} — {e.get('note') or ''}" for e in partial] or ["- (none)"])
    md += ["", "## Explicitly not claimed (out of scope)"]
    md += ([f"- **{e['id']}** — {e['statement']} — {e.get('note') or ''}" for e in notclaimed] or ["- (none)"])
    md += ["", "## Known limitations (from executed evidence)",
           "- Throughput is GIL-bound and does not scale with threads (E4/C9).",
           "- The ULB should-deny denominator (492) gives a wide FPR confidence bound (E1).",
           "- Recognition-set gating cannot flag a known contact weaponized as an exfil sink, and "
           "8 mediated tools are structural-only (E7).",
           "- Ablation and robustness use deterministic constructed workloads (E5/E8), not arbitrary "
           "field distributions.",
           "", "## Future work",
           "- Optionally run E7's live arm (start a local Ollama server) to add agent-side Utility/TASR. "
           "No runtime-governance claim depends on it.",
           "- AgentHarm (pre-registered §IX-F, never implemented) as an optional second external "
           "replication benchmark.",
           "- Multi-process / native substrate to convert safety-under-load into throughput scaling.",
           "- Extend formal mechanization (TLC) to Invariants 2-6 and a larger bounded config.",
           "- A second externally-authored adversarial corpus to strengthen external validity."]
    (ROOT / "LIMITATIONS_AND_NEGATIVE_RESULTS.md").write_text("\n".join(md))


# ---------------------------------------------------------------- Part 10: reproducibility audit
def gen_reproducibility_audit():
    host = _host()
    idx = _run_index()
    exps = idx.get("experiments", {})
    md = ["# REPRODUCIBILITY AUDIT (auto-generated)", "",
          "Everything required to reproduce the evaluation, captured from the execution metadata.", "",
          "## Environment",
          f"- Platform: `{host.get('platform')}`",
          f"- Machine: `{host.get('machine')}` · CPU: `{host.get('cpu_brand')}` · cores: {host.get('cpu_count')}",
          f"- Memory: {round((host.get('mem_bytes') or 0)/1e9, 1)} GB",
          f"- Python: `{host.get('python_version')}` (`{host.get('python_executable')}`)",
          f"- Git HEAD: `{host.get('git_head')}` (dirty: {host.get('git_dirty')})",
          f"- Evaluation seed: `{host.get('eval_seed')}`",
          "- Java/TLC (E3 optional step): Temurin JRE 21 + tla2tools (fetched to ~/.ldrea_tla)",
          "", "## Execution order, timestamps, runtime, and reproduction commands",
          "| Exp | Status | Started (UTC) | Runtime (s) | Reproduction command |",
          "|-----|--------|---------------|-------------|----------------------|"]
    for eid in sorted(exps):
        r = exps[eid]
        md.append(f"| {eid} | {r.get('status')} | {r.get('started_utc')} | {r.get('duration_s')} | "
                  f"`{r.get('reproduction_command')}` |")
    md += ["", "## Artifact checksums (SHA-256)",
           "| Artifact | SHA-256 | bytes |", "|----------|---------|-------|"]
    seen = set()
    for eid in sorted(exps):
        for name, a in (exps[eid].get("artifacts") or {}).items():
            if isinstance(a, dict) and a.get("path") and a["path"] not in seen and a.get("sha256"):
                seen.add(a["path"])
                md.append(f"| `{a['path']}` | `{a['sha256'][:32]}…` | {a.get('bytes')} |")
    md += ["", "## One-command reproduction",
           "```bash", "./.venv/bin/python RUN_ALL_EXPERIMENTS.py        # full suite (E1–E8) + generators",
           "./.venv/bin/python validate_paper_claims.py       # numerical-claim validation",
           "./.venv/bin/python scientific_consistency.py      # consistency + provenance audit", "```"]
    (ROOT / "REPRODUCIBILITY_AUDIT.md").write_text("\n".join(md))


# ---------------------------------------------------------------- Part 8: evidence manifest
def gen_evidence_manifest(evals):
    host = _host()
    idx = _run_index()
    manifest = {"campaign": "ldrea_tier_s_evidence_manifest",
                "host": host, "generated_from": "experiments/_meta/run_index.json + claims registry",
                "claims": []}
    for c, e in zip(CLAIMS, evals):
        entry = {"id": c["id"], "statement": c["statement"], "status": e["status"],
                 "experiments": c.get("experiments", []),
                 "figures": [f"experiments/figures/{f}" for f in c.get("figures", [])],
                 "tables": [f"experiments/tables/{t}" for t in c.get("tables", [])],
                 "evidence": []}
        for chk, res in zip(c.get("evidence", []), e["evidence_checks"]):
            entry["evidence"].append({
                "artifact": chk["artifact"], "pointer": chk["pointer"], "relation": chk["relation"],
                "resolved_value": res["value"], "holds": res["holds"],
                "sha256": EV.sha256_file(chk["artifact"])})
        manifest["claims"].append(entry)
    # global artifact checksum table
    arts = {}
    for eid, r in idx.get("experiments", {}).items():
        for name, a in (r.get("artifacts") or {}).items():
            if isinstance(a, dict) and a.get("path"):
                arts[a["path"]] = {"sha256": a.get("sha256"), "bytes": a.get("bytes"), "experiment": eid}
    manifest["artifact_checksums"] = arts
    manifest["reproduction"] = {"full": "./.venv/bin/python RUN_ALL_EXPERIMENTS.py",
                                "validate": "./.venv/bin/python validate_paper_claims.py",
                                "consistency": "./.venv/bin/python scientific_consistency.py"}
    (ROOT / "evidence_manifest.json").write_text(json.dumps(manifest, indent=2))


