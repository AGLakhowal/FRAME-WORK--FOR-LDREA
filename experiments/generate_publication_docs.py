def main():
    evals = evaluated_claims()
    counts = gen_claim_matrix(evals)
    gen_reviewer_mapping(evals)
    gen_threats(evals)
    gen_limitations(evals)
    gen_reproducibility_audit()
    gen_evidence_manifest(evals)
    gen_final_report(evals, counts)
    print(f"[pub-docs] claims={len(evals)} statuses={counts}")
    print("[pub-docs] wrote CLAIM_EVIDENCE_MATRIX.md, reviewer_mapping.md, THREATS_TO_VALIDITY.md,")
    print("[pub-docs] LIMITATIONS_AND_NEGATIVE_RESULTS.md, REPRODUCIBILITY_AUDIT.md,")
    print("[pub-docs] evidence_manifest.json, FINAL_EVIDENCE_REPORT.md")


if __name__ == "__main__":
    main()
